/// What `-C metadata` hashes, as cargo's `compute_metadata`
/// (`core/compiler/build_runner/compilation_files.rs`) does: the package, its features, the
/// profile, the target's kind and the platform each change it; the sources do not.
/// The exact values against cargo's are held by `plan/tests.rs`.
#[test]
fn the_metadata_changes_with_what_cargo_hashes() {
    let fixture = Fixture::new();
    let manifest = format!("{A}\n[features]\nx = []\n");
    let files = [("ws/Cargo.toml", manifest.as_str()), ("ws/src/lib.rs", "")];
    let metadata = |ask: &Ask<'_>| lib_of(&ready(fixture.plan(fixture.open(ask))), "a").2.metadata.clone();
    let dev = metadata(&ask(&files));
    assert_eq!(dev.len(), 16, "{dev}");
    assert!(dev.chars().all(|it| it.is_ascii_hexdigit()), "{dev}");
    let edited = [("ws/Cargo.toml", manifest.as_str()), ("ws/src/lib.rs", "pub fn f() {}\n")];
    assert_eq!(metadata(&ask(&edited)), dev);
    let release = metadata(&Ask { args: &["--release"], ..ask(&files) });
    let featured = metadata(&Ask { args: &["--features", "x"], ..ask(&files) });
    let targeted = metadata(&Ask { args: &["--target", HOST], ..ask(&files) });
    let all = [&dev, &release, &featured, &targeted];
    for (at, one) in all.iter().enumerate() {
        assert!(all[at + 1..].iter().all(|other| other != one), "{all:?}");
    }
}

#[test]
fn only_a_unit_that_uses_an_artifact_dependency_is_refused() {
    let fixture = Fixture::new();
    let a = format!("{A}\n[dependencies]\nb = {{ path = \"../b\", artifact = \"bin\" }}\n");
    let b = "[package]\nname = \"b\"\nversion = \"0.1.0\"\nedition = \"2024\"\n";
    let c = "[package]\nname = \"c\"\nversion = \"0.1.0\"\nedition = \"2024\"\n";
    let files = [
        ("ws/Cargo.toml", "[workspace]\nmembers = [\"a\", \"b\", \"c\"]\nresolver = \"2\"\n"),
        ("ws/a/Cargo.toml", a.as_str()),
        ("ws/a/src/lib.rs", ""),
        ("ws/b/Cargo.toml", b),
        ("ws/b/src/main.rs", "fn main() {}\n"),
        ("ws/c/Cargo.toml", c),
        ("ws/c/src/lib.rs", ""),
    ];
    let without = failed(fixture.plan(fixture.open(&Ask { args: &["-p", "c"], ..ask(&files) })));
    assert!(without.contains("`artifact = …` requires `-Z bindeps` (b)"), "{without}");

    let c_only = Ask { args: &["-Zbindeps", "-p", "c"], ..ask(&files) };
    let units = ready(fixture.plan(fixture.open(&c_only)));
    assert_eq!(roots_named(&units), ["c lib"]);
    let lock = units.lock.expect("a new lock file").text;
    assert!(lock.contains("name = \"a\"\nversion = \"0.1.0\"\ndependencies = [\n \"b\",\n]\n"), "{lock}");

    let a_too = Ask { args: &["-Zbindeps", "-p", "a"], ..ask(&files) };
    let refused = failed(fixture.plan(fixture.open(&a_too)));
    assert!(refused.contains("(`-Z bindeps`, #601)"), "{refused}");
    assert!(refused.contains("of `a` depends on `b`"), "{refused}");
}

